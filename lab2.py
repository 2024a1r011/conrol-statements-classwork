# Iteration over a list

numbers = [10, 20, 30, 40, 50]

print("List elements:")
for num in numbers:
    print(num)

# Iteration over a dictionary

student = {
    "Name": "Vishavjeet",
    "Age": 20,
    "Course": "CSE"
}

print("\nDictionary elements:")
for key, value in student.items():
    print(key, ":", value)