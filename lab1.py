# Type checking and built-in functions

a = -25
b = [10, 20, 30, 40]
c = 15.678
d = "Python"

print("Type of a:", type(a))
print("Type of b:", type(b))
print("Type of c:", type(c))
print("Type of d:", type(d))

print("Absolute value:", abs(a))
print("Length of list:", len(b))
print("Minimum value:", min(b))
print("Rounded value:", round(c))
print("Is d alphanumeric?", d.isalnum())
print("Type of a:", type(a))